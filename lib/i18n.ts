export type CopyKey = keyof typeof dict;

export function t(locale: Locale, key: CopyKey, vars?: Record<string, string | number>): string {
  let text: string = dict[key][locale];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function fieldLabel(locale: Locale, field: string): string {
  const map: Record<string, CopyKey> = {
    legalName: 'legalName',
    address: 'address',
    vatId: 'vat',
    iban: 'iban',
    bankName: 'bank',
    paymentTermsDays: 'paymentTermsField',
    reachStatus: 'reachStatus',
    rohsStatus: 'rohsStatus',
    lksgSelfAssessment: 'lksgField',
    unitPrice: 'unitPrice',
    moq: 'minimumOrder',
    co2eKg: 'emissions',
    drawingFileId: 'drawing',
  };
  const key = map[field];
  return key ? t(locale, key) : field;
}
